#!/usr/bin/env node
/**
 * Point shared entry re-exports at the active programme pack.
 * Invoked by build/dev scripts before tsc/vite so only one pack is imported.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const raw = (process.argv[2] || process.env.PROGRAMME || 'msba').toLowerCase()
const PACK_IDS = new Set(['msba', 'mgm', 'mecon'])
const id = PACK_IDS.has(raw) ? raw : 'msba'

const packPath = path.join(root, 'src/programmes/activePack.ts')
const localePath = path.join(root, 'src/programmes/activeLocaleOverlays.ts')

const localeImport =
  id === 'mgm'
    ? `./mgm/localeOverlays`
    : id === 'mecon'
      ? `./mecon/localeOverlays`
      : `./emptyLocaleOverlays`

fs.writeFileSync(
  packPath,
  `/** Auto-generated by scripts/select-programme.mjs — do not edit. */\nexport * from './${id}/pack'\n`,
)
fs.writeFileSync(
  localePath,
  `/** Auto-generated by scripts/select-programme.mjs — do not edit. */\nexport { programmeLocaleOverlays } from '${localeImport}'\n`,
)

console.log(`select-programme: ${id}`)
